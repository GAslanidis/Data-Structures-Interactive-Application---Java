    private void btnParseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnParseActionPerformed
        //TODO:[2.1] Create the tree with a root node.
        CTreeNode oRoot = new CTreeNode(true);
        oTree = new CTree(oRoot);
        
        //TODO:[1.3] Loop that dequeues until the queue becomes empty.
        
        CTreeNode oPrevNode = new CTreeNode(false);
        
        while(!oQueuePython.IsEmpty()){
            
            String sTempItem = "";
            
            //TODO:[1.3] Dequeue an show to the console (output) the indentation level and first token of the source code line   
            sTempItem = oQueuePython.Dequeue().toString();
            System.out.println("sTempItem = " + sTempItem + "\n");
            
            CTreeNode oCurrentBranch = new CTreeNode(false, sTempItem);
            System.out.println("Current Name: "+oCurrentBranch.Name+"\n");
            
            //TODO: [2.2] Check the source code line indentation level and add a node for the block/statement. 
            if(sTempItem.startsWith("1")){
                
                oTree.Root.AddChildNode(oCurrentBranch);
                
                
                oPrevNode = oCurrentBranch;
            }
            else{
                
                oPrevNode.AddChildNode(oCurrentBranch);
            }
        }
        
        //TODO:[2.2] Replace empty string with the tree string reprentation.
        this.txtProgramTree.setText(oTree.toString());
    }//GEN-LAST:event_btnParseActionPerformed
