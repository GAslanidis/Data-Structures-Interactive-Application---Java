    private void btnLoadSourceCodeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoadSourceCodeActionPerformed
        
        CTextFile oTextFile = new CTextFile("grade_histogram.py");
        //TODO:[1.1] Use CTextFile to load an array of source code lines.
        oTextFile.LoadArray(oUnArray);
        
        //TODO:[1.1] Replace empty string with the array string reprentation.
        this.txtSourceCode.setText(oUnArray.toString());
        
        //TODO:[1.2] Enqueue all source code lines as CPythonLine objects
        for(int i = 0; i < oUnArray.getItemCount(); i++){
            
            oQueuePython.Enqueue(new CPythonLine(oUnArray.getItem(i)));
        }
        
        //TODO:[1.2] Replace empty string with the queue string reprentation.
        this.txtQueue.setText(oQueuePython.toString());
        
    }//GEN-LAST:event_btnLoadSourceCodeActionPerformed
